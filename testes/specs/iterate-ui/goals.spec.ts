import { test, expect } from '../../harness/fixtures.ts';
import { q } from '../../harness/db.ts';
import { as } from '../../harness/api.ts';
import { PODCAST, oferta } from '../../harness/iterate.ts';
import { loginRapido, semRolagemHorizontal, tela } from '../../harness/navegador.ts';
import { esperarJobsQuietos } from '../../harness/f2.ts';

test.use({ actionTimeout: 30_000 });

test.afterEach(async () => { await esperarJobsQuietos(120_000); });

test('goals → manual categories → add back → saved answers, without a second analysis', async ({ page }, info) => {
  await q(`update workspaces set onboarding_completed_at = now()`);
  await q(`update memberships set tour_completed_at = now()`);
  await q(`update users set account_mode = 'OWN'`);
  await oferta('A');
  await loginRapido(page, 'adminA');
  await page.goto('/iterate/new');
  await page.locator('input[type=file]').first().setInputFiles(PODCAST);
  await page.waitForURL(/\/iterate\/(?!new)[^/?]+/, { timeout: 90_000 });
  const batchId = new URL(page.url()).pathname.split('/')[2];
  await expect(page.getByRole('heading', { name: 'What do you want this batch to do?' })).toBeVisible({ timeout: 90_000 });
  await tela(page, info, 'goals-01-objective');
  await semRolagemHorizontal(page, 'goals objective');
  await page.getByRole('radio', { name: /Reach a new audience/ }).check();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Which variations do you want?' })).toBeVisible();
  await page.getByRole('checkbox', { name: 'New headlines', exact: true }).check();
  await expect(page.getByRole('checkbox', { name: /Let HookMill choose/ })).not.toBeChecked();
  await tela(page, info, 'goals-02-categories');
  await page.getByRole('button', { name: 'See the plan', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Client preferences', exact: true })).toBeVisible({ timeout: 90_000 });
  await expect(page.getByRole('heading', { name: 'Left out of this batch', exact: true })).toBeVisible();
  await expect(page.getByText('YOU ASKED', { exact: true }).first()).toBeVisible();
  await semRolagemHorizontal(page, 'goals plan');
  await tela(page, info, 'goals-03-selected-plan');
  const before = (await as('adminA').get(`/iterate/${batchId}`)).data;
  expect(before.answers).toMatchObject({ goal: 'new_audience', wants: ['headline'], ai: 'free_only' });
  expect(before.pieces.every((p: any) => !p.wantKey || p.wantKey === 'headline')).toBe(true);
  await page.getByRole('button', { name: 'Add back', exact: true }).first().click();
  await expect.poll(async () => (await as('adminA').get(`/iterate/${batchId}`)).data.pieces.length).toBe(before.pieces.length + 1);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Client preferences', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Edit answers', exact: true }).click();
  await expect(page.getByRole('radio', { name: /Reach a new audience/ })).toBeChecked();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: 'New headlines', exact: true })).toBeChecked();
  await page.getByRole('checkbox', { name: /Let HookMill choose/ }).check();
  await expect(page.getByRole('checkbox', { name: 'New headlines', exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: 'See the plan', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Client preferences', exact: true })).toBeVisible();
  const after = (await as('adminA').get(`/iterate/${batchId}`)).data;
  expect(after.cost.analysisUsd).toBe(before.cost.analysisUsd);
  expect(after.pieces.length).toBeLessThanOrEqual(12);
  const next = await as('adminA').post('/iterate', { championId: after.source.championId });
  expect(next.status).toBe(202);
  await page.goto(`/iterate/${next.data.id}`);
  await expect(page.getByRole('button', { name: 'Use saved answers', exact: true })).toBeVisible({ timeout: 90_000 });
  await tela(page, info, 'goals-04-saved-preferences');
  await page.getByRole('button', { name: 'Use saved answers', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Client preferences', exact: true })).toBeVisible({ timeout: 90_000 });
  await page.getByRole('button', { name: 'Forget saved answers', exact: true }).click();
  await expect.poll(async () => (await as('adminA').get('/iterate/config')).data.savedPreferences).toBeNull();
});
