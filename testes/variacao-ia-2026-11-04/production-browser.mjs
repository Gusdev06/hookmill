import { chromium, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
const fixture = JSON.parse(readFileSync('testes/.cache/ai-production/fixture.json', 'utf8'));
const dir = 'reports/templates-ia-background-2026-11-04';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 980 }, baseURL: 'http://localhost:3342', acceptDownloads: true });
const page = await context.newPage();
page.setDefaultTimeout(30000); page.setDefaultNavigationTimeout(90000);
const errors = [], checks = [];
page.on('pageerror', (e) => errors.push(e.message));
await context.route('**/*', (route) => {
  const u = new URL(route.request().url());
  return ['localhost', '127.0.0.1'].includes(u.hostname) || ['data:', 'blob:', 'about:'].includes(u.protocol) ? route.continue() : route.abort();
});
try {
  const login = await context.request.post('/api/session', { data: { email: fixture.email, password: fixture.password } });
  expect(login.ok()).toBeTruthy();
  const session = await login.json();
  await context.request.post('http://localhost:3242/api/v1/workspace/tour/complete', { headers: { Authorization: `Bearer ${session.accessToken}` }, data: {} });
  await page.goto('/ai-variations');
  await expect(page).toHaveURL(/\/templates\?tab=ai$/);
  await expect(page.getByRole('heading', { name: 'Templates', exact: true })).toBeVisible();
  await expect(page.locator('article')).toHaveCount(3);
  await expect(page.getByRole('link', { name: 'Variações com IA', exact: true })).toHaveCount(0);
  checks.push('URL antiga redireciona para With AI; três formatos ativos; menu sem planejador separado');
  await page.screenshot({ path: `${dir}/templates-ai-desktop.png`, fullPage: true });
  await page.getByRole('article', { name: 'Conversa de podcast', exact: true }).getByRole('button', { name: /Usar/ }).click();
  await expect(page).toHaveURL(/\/templates\/podcast-conversation/);
  const champion = page.getByRole('radio').filter({ hasText: 'Organize a semana' });
  await expect(champion).toBeVisible(); await champion.click();
  const generate = page.getByRole('button', { name: 'Gerar vídeo com IA' });
  await expect(generate).toBeEnabled();
  await page.screenshot({ path: `${dir}/choose-champion.png`, fullPage: true });
  const response = page.waitForResponse((r) => r.url().endsWith('/ad-templates/podcast-conversation/use') && r.request().method() === 'POST');
  await generate.click();
  const use = await response; expect(use.status()).toBe(202);
  const batch = (await use.json()).data;
  await expect(page).toHaveURL(new RegExp(`/templates/run/${batch.id}$`));
  await expect(page.getByText('Seu anúncio está sendo transformado neste formato.')).toBeVisible();
  await expect(page.getByText('Planeje suas variações', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: `${dir}/background-progress.png`, fullPage: true });
  checks.push('escolher template → campeão → Gerar inicia produção; nenhum Plan intermediário');
  await page.reload();
  await expect(page).toHaveURL(new RegExp(`/templates/run/${batch.id}$`));
  await expect.poll(async () => {
    const r = await context.request.get(`http://localhost:3242/api/v1/iterate/${batch.id}`, { headers: { Authorization: `Bearer ${session.accessToken}` } });
    return (await r.json()).data.pieces[0]?.status;
  }, { timeout: 90000, intervals: [1000] }).toBe('ready');
  await expect(page.locator('video').first()).toBeVisible();
  await expect.poll(() => page.locator('video').first().evaluate((v) => ({ loaded: v.readyState >= 2, error: v.error?.code ?? null })), { timeout: 30000 }).toEqual({ loaded: true, error: null });
  await page.locator('video').first().evaluate(async (v) => { v.muted = true; await v.play(); });
  await expect.poll(() => page.locator('video').first().evaluate((v) => v.currentTime)).toBeGreaterThan(0.25);
  await page.locator('video').first().evaluate((v) => v.pause());
  await page.screenshot({ path: `${dir}/video-ready-desktop.png`, fullPage: true });
  checks.push('reload retoma produção e entrega vídeo no mesmo endereço');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/templates?tab=ai');
  await expect(page.getByRole('article', { name: 'Conversa de podcast', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: `${dir}/templates-ai-mobile.png`, fullPage: true });
  checks.push('galeria mobile sem overflow');
  expect(errors).toEqual([]);
  writeFileSync(`${dir}/browser-checks.json`, JSON.stringify({ checks, errors, mode: 'mock', at: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
} catch (e) {
  await page.screenshot({ path: `${dir}/browser-failure.png`, fullPage: true });
  writeFileSync(`${dir}/browser-failure.txt`, await page.locator('body').innerText());
  throw e;
} finally { await browser.close(); }
